"""TrustLens Collaborative Threat Intelligence — Enumerations and Core Concepts.

Defines module-local domain concepts, threat categories, indicator scopes,
lifecycle statuses, evidence stances, and moderation actions.
These concepts are isolated to this intelligence engine and do not modify
canonical backend database models.
"""

from __future__ import annotations

from enum import Enum


class ThreatCategory(str, Enum):
    """Categorization of community-reported threats."""

    PHISHING = "PHISHING"
    MALWARE = "MALWARE"
    SCAM = "SCAM"
    SPAM = "SPAM"
    IMPERSONATION = "IMPERSONATION"
    SUSPICIOUS_REDIRECT = "SUSPICIOUS_REDIRECT"
    CREDENTIAL_HARVESTING = "CREDENTIAL_HARVESTING"
    OTHER = "OTHER"

    @classmethod
    def from_string(cls, value: str) -> ThreatCategory:
        """Safely parse category from any case or alias."""
        clean = (value or "").strip().upper()
        # Common aliases from backend or external systems
        alias_map = {
            "PHISH": cls.PHISHING,
            "PHISHING": cls.PHISHING,
            "MALWARE": cls.MALWARE,
            "SCAM": cls.SCAM,
            "SPAM": cls.SPAM,
            "IMPERSONATION": cls.IMPERSONATION,
            "SUSPICIOUS_REDIRECT": cls.SUSPICIOUS_REDIRECT,
            "REDIRECT": cls.SUSPICIOUS_REDIRECT,
            "CREDENTIAL_HARVESTING": cls.CREDENTIAL_HARVESTING,
            "HARVESTING": cls.CREDENTIAL_HARVESTING,
            "UNSOLICITED_BULK": cls.SPAM,
        }
        return alias_map.get(clean, cls.OTHER)


